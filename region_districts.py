def find_district(region: str, place: str) -> str:
    """place 텍스트에서 region에 속한 시/군 이름을 찾아 반환. 못 찾으면 빈 문자열.

    실제 place 텍스트엔 "순천시" 대신 "순천"처럼 접미사(시/군) 없이 적힌
    경우가 훨씬 많아서(예: "여수 화정면...", "나주종합스포츠파크"), 접미사를
    뗀 이름("순천")으로도 매칭을 시도한다 - 매칭되면 항상 접미사 붙은 정식
    이름("순천시")으로 반환해서 표시를 통일한다. region으로 이미 후보를
    좁혀놓은 상태라 지역 내 이름 충돌은 실질적으로 없다."""
    if not place:
        return ""
    candidates = DISTRICTS_BY_REGION.get(region, [])
    full_matches = [d for d in candidates if d in place]
    if full_matches:
        return max(full_matches, key=len)
    base_matches = [d for d in candidates if d[:-1] in place]
    if not base_matches:
        return ""
    return max(base_matches, key=len)
